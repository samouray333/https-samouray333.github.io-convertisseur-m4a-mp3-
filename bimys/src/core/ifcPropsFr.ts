/** Nom français d'un jeu de propriétés (Pset / Qto), sinon le nom d'origine rendu lisible. */
export function psetFr(name: string): string {
  if (PSET[name]) return PSET[name];
  return name.replace(/^(Pset|Qto)_/, '').replace(/([a-z])([A-Z])/g, '$1 $2');
}

export function propFr(name: string): string {
  return PROP[name] ?? name;
}

/** Valeur énumérée (MAJUSCULES) traduite si elle est connue. */
export function valueFr(v: string): string {
  return VAL[v] ?? v;
}

export function isTranslatedProp(name: string): boolean {
  return name in PROP;
}
