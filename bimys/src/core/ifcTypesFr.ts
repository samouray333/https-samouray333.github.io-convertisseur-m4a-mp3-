export function ifcFr(cls: string): string {
  if (FR[cls]) return FR[cls];
  // essai insensible à la casse (web-ifc renvoie parfois IFCPIPESEGMENT)
  const k = Object.keys(FR).find((x) => x.toLowerCase() === cls.toLowerCase());
  return k ? FR[k] : cls.replace(/^Ifc/, '');
}

